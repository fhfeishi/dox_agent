def model_failure_message(exc: BaseException, timeout_hint: str) -> str:
    """A readable reason for a failed model call; the provider's own text stays in the log."""
    name = type(exc).__name__
    if "Timeout" in name:
        return timeout_hint
    if "Connection" in name:
        return "无法连接模型服务（DNS 或网络不可达）。模型调用始终直连、不经代理，请检查本机网络与 MODEL_BASE_URL"
    if name in ("AuthenticationError", "PermissionDeniedError", "RateLimitError"):
        return "模型服务拒绝了请求（密钥或额度），请联系管理员"
    return ""


def duplicate_sources(manifest: dict[str, dict]) -> dict[str, str]:
    """Files whose content equals an earlier one, mapped to that file (query 2026-1016 1814: a copy
    under another name is pointed out, and the user keeps or deletes it)."""
    first: dict[str, str] = {}
    copies: dict[str, str] = {}
    for rel, entry in sorted(manifest.items(), key=lambda item: (item[1].get("updated_at") or "", item[0])):
        digest = entry.get("sha256") or ""
        if not digest:
            continue
        if digest in first:
            copies[rel] = first[digest]
        else:
            first[digest] = rel
    return copies


def sse(event: str, data: object) -> str:
    return f"event: {event}\ndata: {json.dumps(data, ensure_ascii=False)}\n\n"


def prune_web_entries(entries: dict, now: datetime, *, limit: int = 20) -> dict:
    """Bound short-lived URL previews and search result sets for the single-user app."""
    fresh = {key: value for key, value in entries.items() if value["expires_at"] > now}
    if len(fresh) <= limit:
        return fresh
    newest = sorted(fresh.items(), key=lambda item: item[1]["expires_at"], reverse=True)
    return dict(newest[:limit])

